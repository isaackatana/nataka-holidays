import { supabase } from '@/lib/supabase'
import { prepareImageForUpload } from '@/utils/image'

export interface ReviewImage {
  id: string
  storage_path: string
}

export interface Review {
  id: string
  rating: number
  comment: string | null
  created_at: string
  owner_reply: string | null
  review_images: ReviewImage[]
  profiles: { full_name: string | null } | null
}

export async function getApprovedReviews(propertyId: string): Promise<Review[]> {
  const { data, error } = await supabase
    .from('reviews')
    .select('id, rating, comment, created_at, owner_reply, review_images ( id, storage_path ), profiles ( full_name )')
    .eq('property_id', propertyId)
    .eq('status', 'approved')
    .order('created_at', { ascending: false })

  if (error) throw error
  return (data ?? []) as unknown as Review[]
}

export const REVIEW_COMMENT_MAX = 1000

export interface MyReview {
  id: string
  booking_id: string | null
  property_id: string
  rating: number
  comment: string | null
  status: 'pending' | 'approved' | 'rejected'
  created_at: string
  review_images: ReviewImage[]
}

/** The signed-in guest's own reviews, any status (RLS allows own + approved). */
export async function getMyReviews(customerId: string): Promise<MyReview[]> {
  const { data, error } = await supabase
    .from('reviews')
    .select('id, booking_id, property_id, rating, comment, status, created_at, review_images ( id, storage_path )')
    .eq('customer_id', customerId)
    .order('created_at', { ascending: false })

  if (error) throw error
  return (data ?? []) as unknown as MyReview[]
}

export interface SubmitReviewInput {
  /** Generated by the caller so photos can be attached right after. */
  id: string
  customerId: string
  propertyId: string
  bookingId: string
  rating: number
  comment: string
}

/** Server trigger forces status = 'pending' and checks the stay is the guest's own. */
export async function submitReview(input: SubmitReviewInput): Promise<void> {
  const { error } = await supabase.from('reviews').insert({
    id: input.id,
    customer_id: input.customerId,
    property_id: input.propertyId,
    booking_id: input.bookingId,
    rating: input.rating,
    comment: input.comment.trim() || null,
  } as never)
  if (error) throw error
}

/** An edit sends the review back to moderation (enforced by the DB trigger). */
export async function updateMyReview(
  id: string,
  rating: number,
  comment: string,
): Promise<void> {
  const { error } = await supabase
    .from('reviews')
    .update({ rating, comment: comment.trim() || null } as never)
    .eq('id', id)
  if (error) throw error
}

export interface PropertyRating {
  property_id: string
  average: number
  review_count: number
}

/** Average rating + approved-review count per property (one request for all). */
export async function getPropertyRatings(): Promise<Record<string, PropertyRating>> {
  const { data, error } = await supabase.rpc('property_rating_stats' as never)
  if (error) throw error
  const rows = (data ?? []) as unknown as { property_id: string; average: number | string; review_count: number }[]
  const map: Record<string, PropertyRating> = {}
  for (const row of rows) {
    map[row.property_id] = {
      property_id: row.property_id,
      average: Number(row.average),
      review_count: Number(row.review_count),
    }
  }
  return map
}

const REVIEW_BUCKET = 'review-images'

/** Shrinks and uploads one review photo, then records it against the review. */
export async function uploadReviewImage(customerId: string, reviewId: string, file: File): Promise<void> {
  const optimized = await prepareImageForUpload(file)
  const ext = optimized.type === 'image/webp' ? 'webp' : optimized.type === 'image/png' ? 'png' : 'jpg'
  // Random name inside the guest's own folder (storage rules require that folder).
  const path = `${customerId}/${crypto.randomUUID()}.${ext}`

  const { error: uploadError } = await supabase.storage.from(REVIEW_BUCKET).upload(path, optimized, {
    cacheControl: '31536000',
    upsert: false,
  })
  if (uploadError) throw uploadError

  const { error: insertError } = await supabase
    .from('review_images')
    .insert({ review_id: reviewId, storage_path: path } as never)
  if (insertError) {
    await supabase.storage.from(REVIEW_BUCKET).remove([path]) // don't leave an orphan file
    throw insertError
  }
}

/** Removes a photo (file and row). Either side failing is reported. */
export async function deleteReviewImage(image: ReviewImage): Promise<void> {
  const { error: rowError } = await supabase.from('review_images').delete().eq('id', image.id)
  if (rowError) throw rowError
  const { error: fileError } = await supabase.storage.from(REVIEW_BUCKET).remove([image.storage_path])
  if (fileError) console.error('[deleteReviewImage] could not remove file:', fileError)
}
